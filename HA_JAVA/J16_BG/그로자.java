package J16_BG;

public class 그로자 extends Weapon {
    // ---------------------------------------
    // 필드 - 적을거 없음
    String 탄약종류;
    // ---------------------------------------
    // 생성자 - 부모님 뵙고 와야함
    그로자(String name){
        super(1, name);
        // -----------------------
        // 이제 맘에 안드는 나만의 필드 세팅 진행
        this.탄창 = 30;
        this.최대탄창 = 30;
        this.등장확률 = 0;
        
        this.초당데미지 = 9;
        this.연사속도 = 8;

        this.탄약종류 = "7.62mm";
    }
    // ---------------------------------------
    @Override 
    void 발사(){
        if(this.탄창>=1){
            // 발사 가능
            System.out.println("퍗");
            this.탄창--;
        }else{
            // 발사 불가능 -> 재장전
            재장전();
        }
    }

    void 전체발사(){
        // 탄창내 남은 총알들 모두 발사
        for(int i=this.탄창; i>=1; i--){
            System.out.print("퍗");
            this.탄창--;
        }
        재장전();
    }
}
