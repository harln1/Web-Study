public class J03_ChangeType {
    public static void main(String[] args) {
        // < 형변환 >
        // 1. 자동 형 변환
        // 변수 = 변수
        // 큰놈 = 작은놈 -> ㅇㅋ
        // 작은놈 = 큰놈 -> 손실 = 에러
        // double big = 1234.56789;
        // // int small = big;
        // int small = 1234;
        // big = small; // 1234.0
        // ★★★★ 정수와 정수의 연산은 정수!!!
        System.out.println(20 + 10); // 30
        System.out.println(20 - 10); // 10
        System.out.println(20 * 10); // 200
        System.out.println(20 / 10); // 2
        System.out.println(20 / 10.0); // 2.0
        System.out.println(20 % 10); // 0
        System.out.println(20 % 11); // 9
        System.out.println(20 % 12); // 8


        // 2. 강제 형 변환
        // (자료형)변수또는 값
    }
}
