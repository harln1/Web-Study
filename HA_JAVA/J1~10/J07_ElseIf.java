import java.util.Random;

public class J07_ElseIf {
    public static void main(String[] args) {
        int 딸기가격 = 120;
        int 감자가격 = 80;
        int 콜리플라워가격 = 175;
        //int 파스닙 = 35;
        int 골드 = 75;

        if(골드 >= 콜리플라워가격){
            System.out.println("콜리플라워 ㄳㄳ");
            골드 = 골드 - 콜리플라워가격; // 골드 -= 콜리플라워가격;
        }
        else if(골드 >= 딸기가격){
            System.out.println("딸기가 조아 딸기가 조아 ㄳㄳ");
            골드 = 골드 - 딸기가격; // 골드 -= 딸기가격;
        }
        else if(골드 >= 감자가격){
            System.out.println("포테이토오오오");
            골드 -= 감자가격;
        }
        else{
            System.out.println("대변경단 먹어라!");
        }
        // 나머지 작물들을 비싼순으로 else if로 구매가능한지 물어보기
        // 구매 가능하면 한마디 해주고 골드를 감소시키기.
        // 단, 모든 작물을 구매할 수 없다면 "대변경단" 을 출력하세요
        // ----------------------------------------------------
        // < 장비 강화 >
        // 50% 성공, 50% 실행
        // 1~100 공중 하나를 꺼냄 -> 1~50 성공, 51~100 실패
        // 3% 성공, 97% 실패
        // 1~100 공중 하나를 꺼냄 -> 1~3성공, 나머지 실패
        // 0.003% SSS탈것
        // 1~100000 -> 1~3 성공, 나머지 실패
        int 성공확률 = 30;
        // int 실패확률 = 100 - 성공확률;
        String 장비 = "그레이트 소드";
        Random rand = new Random();
        if(rand.nextInt(100)+1 <= 성공확률 ){
            장비 = "찬란한 " + 장비;
        }
        else{
            장비 = "대변경단";
        }
        System.out.println("나의 장비 : " + 장비);
    }
}
